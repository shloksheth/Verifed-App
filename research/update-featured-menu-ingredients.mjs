import { readFileSync, writeFileSync } from "node:fs";
import { publishedMenus } from "../mobile/src/restaurant-menus.js";

const evidence = JSON.parse(readFileSync(new URL("./menu-sources/chipotle-featured-evidence.json", import.meta.url), "utf8"));
const sourcePath = new URL("./full-menu-data.json", import.meta.url);
const source = JSON.parse(readFileSync(sourcePath, "utf8"));

// Apply only the two facts actually read from the cited U.S. primary sources.
// The historical generator points at an older workspace, so update this
// checkout's reviewed source and generated module together.
for (const menus of [source.restaurants, publishedMenus]) {
  const menu = menus.find((menu) => menu.key === "chipotle-south-orange");
  for (const fact of evidence.items) {
    const item = menu.items.find((item) => item.key === fact.key);
    if (!item) throw new Error(`Unknown Chipotle component: ${fact.key}`);
    item.ingredients = fact.ingredients;
    item.description = fact.description;
    item.ingredientSourceUrl = fact.sourceUrl;
    item.ingredientEvidenceNote = fact.note;
    // Do not duplicate the note when reproducing the update.
    const marker = " Published ingredient detail:";
    item.evidenceNote = item.evidenceNote.split(marker)[0] + marker + " " + fact.note;
  }
}
writeFileSync(sourcePath, JSON.stringify(source, null, 2) + "\n");
writeFileSync(new URL("../mobile/src/restaurant-menus.js", import.meta.url),
  "// Generated by research/build-menu-catalog.mjs; edit its reviewed JSON sources.\n" +
  "export const publishedMenus = " + JSON.stringify(publishedMenus, null, 2) + ";\n");
console.log("Updated two source-backed Chipotle ingredient records; refresh photo specifications before approval.");
